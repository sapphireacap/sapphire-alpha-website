"""Regression tests for the P&F pattern/indicator libraries.

Where the book ("Trading The Markets The Point & Figure Way", Prashant
Shah) gives an explicit worked example with real numbers, that example is
transcribed here BY HAND from the text — not generated by running the
code — so these tests are genuine ground truth and not a snapshot of
whatever the implementation happens to do. That is the same discipline
tests/test_pnf_engine.py already applies to chart construction.

Columns are constructed directly rather than via build_columns(): the
construction rules already have their own regression suite, and building
them by hand lets each pattern test state exactly the geometry the book
describes (e.g. the High Pole example's X column spanning box-prices
70..140, which is 8 boxes).
"""
import pytest

from pnf_engine import BoxSettings, Column
import pnf_patterns as pf
import pnf_indicators as pi

BOX10 = BoxSettings(reversal_boxes=3, box_value=10.0)


def X(low: int, high: int) -> Column:
    """An X column spanning [low, high] in box levels."""
    return Column("up", low, high, 1.0)


def O(high: int, low: int) -> Column:
    """An O column spanning [low, high], travelling downward."""
    return Column("down", high, low, 1.0)


