def test_bull_trap_is_a_sell_immediately_after_a_buy():
    # O,X(buy),O(sell) preceded by an O to compare against.
    cols = [O(8, 4), X(5, 7), O(6, 3), X(4, 9), O(8, 2)]
    assert pf.is_double_top_buy(cols, 3)
    p = pf.detect_bull_trap(cols, 4)
    assert p is not None and p.bias == "bearish"
    # "the basic Buy-Sell signal and pattern failure level is the same" —
    # it fails on the next Double Top Buy, above the trapped X column.
    assert p.failure_level == 10


def test_bear_trap_is_a_buy_immediately_after_a_sell():
    cols = [X(2, 8), O(7, 4), X(5, 6), O(5, 3), X(4, 7)]
    assert pf.is_double_bottom_sell(cols, 3)
    p = pf.detect_bear_trap(cols, 4)
    assert p is not None and p.bias == "bullish"
    assert p.failure_level == 2


