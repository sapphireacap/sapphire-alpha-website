def test_prism_alphas_own_column_builder_shares_the_absolute_grid():
    """blackbox_prism_alpha keeps its OWN column-tracking loop (it carries
    per-column timestamps and prices that pnf_engine.Column doesn't), so
    the absolute-grid correction had to be applied there separately — it
    is not inherited. This pins that the two stay in agreement.

    Box sizes differ per module by design (1% there, 0.5%/3% for the
    Index Vector legs, 0.25% default in the Studio); only the CONSTRUCTION
    RULE is shared."""
    import math

    from blackbox_prism_alpha import BOX_PCT, build_pnf_columns

    prices = [100, 103, 101, 106, 104, 110, 107, 113, 109, 116, 112, 119]
    bars = [{"ts": f"3107202609{n:02d}", "close": p} for n, p in enumerate(prices)]

    full = build_pnf_columns(bars)
    trimmed = build_pnf_columns(bars[4:])

    # Trimming the front of the series must not move the box grid.
    assert full[-1]["high_box_price"] == pytest.approx(trimmed[-1]["high_box_price"])
    assert full[-1]["low_box_price"] == pytest.approx(trimmed[-1]["low_box_price"])

    # And every box price sits exactly on a power of (1 + box_pct).
    scale = math.log(1.0 + BOX_PCT)
    for c in full:
        for key in ("high_box_price", "low_box_price"):
            lvl = math.log(c[key]) / scale
            assert lvl == pytest.approx(round(lvl), abs=1e-9)


def test_every_registered_detector_is_callable_at_every_index():
    cols = [X(1, 5), O(4, 2), X(3, 6), O(5, 1), X(2, 9), O(8, 3), X(4, 11)]
    for name, fn in pf.DETECTORS.items():
        for i in range(len(cols)):
            fn(cols, i, pf.DEFAULT_CONFIG)  # must not raise
