def test_follow_through_may_come_later_but_not_after_failure():
    cols = [X(1, 6), O(5, 3), X(4, 6), O(5, 2), X(3, 8)]
    trip = pf.detect_triple_top_buy(cols, 4)
    # No follow-through yet.
    assert pf.find_follow_through(cols, trip) is None
    # A later Double Top Buy, pattern still intact -> follow-through.
    later = cols + [O(7, 5), X(6, 10)]
    ft = pf.find_follow_through(later, trip)
    assert ft is not None and ft.index == 6 and ft.bias == "bullish"
    # If price breaks the pattern's low first, no follow-through.
    failed = cols + [O(7, 0), X(1, 12)]
    assert pf.find_follow_through(failed, trip) is None
    assert pf.has_failed(failed, trip) == 5


