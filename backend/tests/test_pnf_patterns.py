def test_top_bottom_and_boxcount_are_direction_independent():
    assert pf.top(X(7, 14)) == 14 and pf.bottom(X(7, 14)) == 7
    assert pf.top(O(14, 7)) == 14 and pf.bottom(O(14, 7)) == 7
    # Book 2.1 High Pole example: "The total number of boxes in the column
    # of X is 8" for a column spanning box-prices 70 to 140 (box = 10).
    assert X(7, 14).box_count == 8
    # "Mid-box-price of column: (High Box-price + Low Box-price)/2" -> 105.
    assert pf.mid_level(X(7, 14)) == 10.5
    assert BOX10.price_at(pf.mid_level(X(7, 14))) == 105.0
    # On an absolute box-value chart the two agree exactly.
    assert pf.mid_price(X(7, 14), BOX10) == 105.0


def test_mid_price_is_the_arithmetic_mean_of_prices_on_a_log_chart():
    """Ground truth from the real platform's commentary panel (NIFTY
    24400 CE, 3% x 3, 31-Jul-2026): a column running 291.57..309.33 is
    reported MidVal 300.45, and one running 283.08..318.61 is reported
    300.85. Both are the ARITHMETIC mean of the two prices.

    Averaging box LEVELS instead and converting back yields the geometric
    mean (300.32 for both of those columns) — visibly wrong, and it
    biases every Pole's 50%-retracement test. This is the bug that check
    caught."""
    s = BoxSettings(reversal_boxes=3, box_pct=0.03)
    # The real column is 3 boxes: 291.57 -> 300.32 -> 309.33. Derive the
    # top from the bottom rather than resolving each price separately,
    # since either rounding direction can slip a box on an exact boundary.
    lo = s.level_down(291.57)
    hi = lo + 2
    col = Column("down", hi, lo, 1.0)
    assert s.price_at(lo) == pytest.approx(291.57, abs=0.02)
    assert s.price_at(hi) == pytest.approx(309.33, abs=0.02)
    assert pf.mid_price(col, s) == pytest.approx(300.45, abs=0.02)
    # The level-space midpoint is the geometric mean — not what the
    # platform reports.
    assert s.price_at(pf.mid_level(col)) == pytest.approx(300.32, abs=0.02)


