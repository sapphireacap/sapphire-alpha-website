def test_triple_top_buy_requires_two_equal_highs_then_breakout():
    cols = [X(1, 6), O(5, 3), X(4, 6), O(5, 2), X(3, 8)]
    p = pf.detect_triple_top_buy(cols, 4)
    assert p is not None and p.bias == "bullish"
    assert p.trigger_level == 7          # one box above the shared high of 6
    assert p.start_index == 0
    # "the pattern does not fail unless price falls below the lowest O in
    # the pattern" — the lowest print here is 1, so failing it needs a
    # print at 0, one box below.
    assert p.failure_level == 0


def test_triple_top_rejects_unequal_shoulders():
    cols = [X(1, 6), O(5, 3), X(4, 7), O(6, 2), X(3, 9)]
    assert pf.detect_triple_top_buy(cols, 4) is None


def test_triple_bottom_sell_mirrors():
    cols = [O(9, 4), X(5, 7), O(6, 4), X(5, 8), O(7, 2)]
    p = pf.detect_triple_bottom_sell(cols, 4)
    assert p is not None and p.bias == "bearish"
    assert p.trigger_level == 3
    assert p.failure_level == 10


